#!/usr/bin/env bash
# Workspace: PRD, recorded Go confirmation, and a partial final task list.
set -euo pipefail

git init -q
git config user.email "dev@example.com"
git config user.name "Dev"

mkdir -p tasks

cat > tasks/prd-kyc-refresh.md << 'EOF'
# PRD: KYC Watchlist Refresh

## Introduction
customer.json records drift from the sanctions watchlist. A refresh
service should re-screen every customer record nightly and expose the
resulting status through the customer API.

## Goals
- Re-screen all customer records within a four-hour nightly window.
- Surface watchlist status on the customer API without breaking clients.

## User Stories
- As a compliance analyst, I want nightly re-screening so that stale
  approvals are caught within a day.
- As an API client, I want the watchlist status included so that I can gate
  onboarding flows.

## Functional Requirements
1. The system must re-screen every active customer record nightly.
2. The system must update each record's watchlist status field.
3. The system must include watchlist status in the customer API response.
4. The system must log every status change to an append-only audit log.

## Non-Goals (Out of Scope)
- Real-time transaction screening.

## Success Metrics
- 100% of active records re-screened nightly.
- Zero API contract breaks across one release cycle.

## Open Questions
- Which watchlist provider feed do we license?
EOF

cat > go-ahead.md << 'EOF'
# Planning session log

Phase 1 parent tasks generated by assistant 2026-04-02.

Assistant: I have generated the high-level tasks based on the PRD. Ready to
generate the sub-tasks? Respond with 'Go' to proceed.

User: Go
EOF

cat > tasks/tasks-prd-kyc-refresh.md << 'EOF'
# Task list for KYC Watchlist Refresh (partial)

## Relevant Files

(pending)

## Tasks

- [ ] 1.0 Nightly screening job
- [ ] 2.0 Watchlist status storage and API
- [ ] 3.0 Audit logging
EOF

echo "PRD, Go confirmation, and partial task list in place."
